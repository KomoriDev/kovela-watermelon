import {build} from "esbuild";
import {mkdir,readFile} from "node:fs/promises";
import {fileURLToPath} from "node:url";
import path from "node:path";
const root=fileURLToPath(new URL("../",import.meta.url));
const application=path.resolve(root,process.argv[2]||"../watermelon");
const manifest=JSON.parse(await readFile(path.join(application,"src/manifest.json"),"utf8"));
if(manifest.package!=="com.komoridev.watermelon") throw new Error("Target must be the Watermelon Vela application");
await mkdir(path.join(application,"src/skin"),{recursive:true});
await build({stdin:{contents:`import file from "@system.file";import interconnect from "@system.interconnect";import {createSkins} from "./wearable/src/index.js";export default createSkins({file,interconnect});`,resolveDir:root,sourcefile:"skin-entry.js",loader:"js"},
  outfile:path.join(application,"src/skin/index.js"),bundle:true,platform:"browser",format:"esm",target:"es2015",minify:true,
  external:["@system.file","@system.interconnect"],legalComments:"eof",banner:{js:"// Generated by kovela-watermelon scripts/prepare-vela.mjs; edit wearable/src, not this file. Free skin transport; no license verification."}});
console.log("Prepared free Watermelon skin transport");
